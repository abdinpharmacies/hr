                                line_ctx["to_store_sql_id"],
                                line_ctx["product_sql_id"],
                                line_ctx["class_id"],
                                line_ctx["qty"],
                                line_ctx["expiry_date"],
                                line_ctx["insert_user_sql_id"],
                                line_ctx["sell_price"],
                                line_ctx["cost"],
                                0,
                                line_ctx["uom_sql_id"],
                                line_ctx["current_stock"],
                                line_ctx["purchase_price"],
