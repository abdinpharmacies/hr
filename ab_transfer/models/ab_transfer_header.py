    @api.constrains("from_store_id", "to_store_id")
    def _check_store_difference(self):
        for rec in self:
            if rec.from_store_id and rec.to_store_id and rec.from_store_id == rec.to_store_id:
                raise ValidationError(_("Source store and destination store cannot be the same."))

    @api.constrains("from_store_id")
    def _check_source_store_allowed(self):
        store_ids = self._get_allowed_source_store_ids()
        if not store_ids:
            return
        for rec in self:
            if rec.from_store_id and rec.from_store_id.id not in store_ids:
                raise ValidationError(
                    _("Source store %s is not allowed for sales POS.") % rec.from_store_id.display_name)

    @api.constrains("line_ids")
    def _check_lines_exist_when_saved(self):
        for rec in self:
            if rec.selection in ("pending", "saved") and not rec.line_ids:
                raise ValidationError(_("You cannot continue without lines."))

    def _check_not_is_submitted(self):
        locked = self.filtered("is_submitted")
        if locked:
            raise UserError(_("Submitted transfers cannot be edited."))

    def write(self, vals):
        if vals and any(rec.is_submitted for rec in self):
            allowed_after_submit = {
                "error_message",
            }
            if set(vals) - allowed_after_submit:
                self._check_not_is_submitted()
        return super().write(vals)

    def unlink(self):
        self._check_not_is_submitted()
        return super().unlink()

