    def _auto_init(self):
        for old_name, new_name in {
            "sent_to_eplus": "is_submitted",
            "eplus_sent_at": "sent_at",
            "eplus_error_message": "error_message",
        }.items():
            if (
                    column_exists(self.env.cr, self._table, old_name)
                    and not column_exists(self.env.cr, self._table, new_name)
            ):
                rename_column(self.env.cr, self._table, old_name, new_name)
        return super()._auto_init()

    @api.model
    def _get_allowed_source_store_ids(self):
        try:
            replica_db = self.env["ab_replica_db"].sudo().get_current_from_config()
        except Exception:
            return []
        if not replica_db:
            return []
        return replica_db.allowed_sales_store_ids.filtered("allow_sale").ids

    @api.model
    def _get_allowed_source_store_domain(self):
        domain = [("allow_sale", "=", True)]
        store_ids = self._get_allowed_source_store_ids()
        if store_ids:
            domain.append(("id", "in", store_ids))
        return domain

    @api.model
    def _get_default_source_store(self):
        try:
            replica_db = self.env["ab_replica_db"].sudo().get_current_from_config()
        except Exception:
            return self.env["ab_store"].browse()
        if not replica_db or not replica_db.default_sales_store_id:
            return self.env["ab_store"].browse()
        store = replica_db.default_sales_store_id
        allowed_store_ids = self._get_allowed_source_store_ids()
        if store.allow_sale and (not allowed_store_ids or store.id in allowed_store_ids):
            return store
        return self.env["ab_store"].browse()

    @api.model
    def _default_from_store_id(self):
        store = self._get_default_source_store()
        return store.id if store else False

    @api.model
    def _default_user_id(self):
        if "ab_hr_employee" not in self.env.registry:
            return False
        employee = self.env["ab_hr_employee"].sudo().search(
            [
                ("user_id", "=", self.env.user.id),
                ("costcenter_id", "!=", False),
            ],
            limit=1,
        )
        return employee.costcenter_id.id if employee and employee.costcenter_id else False

    @api.depends("from_store_id", "to_store_id")
    def _compute_display_name(self):
        for rec in self:
            if rec.id:
                rec.display_name = _("Transfer %s") % rec.id
