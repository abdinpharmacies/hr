    def rebuild_derived_fields(self):
        self.env.invalidate_all()
        for model in self.prepared:
            records = self.env[model]
            if records._parent_store:
                records._parent_store_compute()
            original = self.manifest['tables'][self.models[model]['table']]['columns']
            fields = [name for name, field in records._fields.items()
                      if field.store and field.compute and name not in original
                      and field.type not in ('one2many', 'many2many')]
            if not fields:
                continue
            print(f'Rebuild target-only derived fields: {model}: {", ".join(fields)}', flush=True)
            after = 0
            while True:
                batch = records.search([('id', '>', after)], order='id', limit=2000)
                if not batch:
                    break
                after = batch[-1].id
                for name in fields:
                    self.env.add_to_compute(records._fields[name], batch)
                batch._recompute_recordset(fields)
                self.env.flush_all()
                self.env.invalidate_all()
        self.env.flush_all()

