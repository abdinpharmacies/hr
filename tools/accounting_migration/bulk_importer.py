    def early_validation(self):
        problems = []
        for model, meta in self.models.items():
            if model in LOOKUPS:
                continue
            target = self.schema.get(model)
            if not target:
                problems.append(dict(model=model, error='Missing target model'))
                continue
            columns = self.manifest['tables'][meta['table']]['columns']
            physical = self.physical[target['table']]
            for field in columns.keys() & physical.keys():
                tf = target['fields'].get(field, {})
                if field in FRAMEWORK or field == 'id':
                    continue
                checks = []
                if physical[field].get('required') and not columns[field].get('required'):
                    checks.append(sql.SQL('{} IS NULL').format(ident(field)))
                if tf.get('selection') and tf.get('type') == meta.get('fields', {}).get(field, {}).get('ttype'):
                    checks.append(sql.SQL('{} IS NOT NULL AND NOT ({}=ANY({}))').format(
                        ident(field), ident(field), sql.Literal(tf['selection'])))
                for condition in checks:
                    self.execute(sql.SQL('SELECT count(*) FROM {} WHERE {}').format(self.src(model), condition))
                    count = self.cr.fetchone()[0]
                    if count:
                        self.execute(sql.SQL('SELECT id FROM {} WHERE {} ORDER BY id LIMIT 10').format(self.src(model),
                                                                                                       condition))
                        problems.append(
                            dict(model=model, field=field, count=count, ids=[r[0] for r in self.cr.fetchall()]))
        save_json(self.stage / 'preflight-errors.json', problems)
        if problems:
            raise MigrationError(f'{len(problems)} schema/required-value issues; see preflight-errors.json')

